    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
  name_catego = name_categoria.getText().trim();
    categoria cat = new categoria();

    if (name_catego.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Por favor ingresa un nombre de categoría.",
                "Campo vacío",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Si no cambió nada, simplemente cerrar
    if (name_catego.equalsIgnoreCase(nombreOriginal)) {
        SwingUtilities.getWindowAncestor(this).dispose();
        return;
    }

    // Verificar si ya existe otra categoría con ese nombre
    if (cat.categoryExists(name_catego)) {
        UIManager.put("OptionPane.background", new Color(255, 255, 255));
        UIManager.put("Panel.background", new Color(255, 255, 255));
        UIManager.put("OptionPane.messageForeground", Color.BLACK);
        UIManager.put("Button.background", new Color(244, 67, 54));
        UIManager.put("Button.foreground", Color.WHITE);
        UIManager.put("Button.focus", new Color(255, 205, 210));

        String message = "<html><body style='text-align:center; font-size:13px;'>"
                + "<b style='color:#D32F2F;'>⚠ Categoría ya existente</b><br>"
                + "Intenta con un nombre diferente."
                + "</body></html>";

        Icon icon = UIManager.getIcon("OptionPane.warningIcon");

        JOptionPane.showMessageDialog(
                this,
                message,
                "Advertencia",
                JOptionPane.WARNING_MESSAGE,
                icon
        );
        return;
    }

    // Obtener id de la categoría original
    int idCat = cat.getCategoryIdByName(nombreOriginal);

    if (idCat == -1) {
        JOptionPane.showMessageDialog(this,
                "No se encontró la categoría a modificar.",
                "Error",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Actualizar en BD
    if (cat.updateCategoryName(idCat, name_catego)) {
        // Mensaje de éxito
        UIManager.put("OptionPane.background", new Color(232, 245, 233));
        UIManager.put("Panel.background", new Color(232, 245, 233));
        UIManager.put("OptionPane.messageForeground", Color.BLACK);
        UIManager.put("Button.background", new Color(76, 175, 80));
        UIManager.put("Button.foreground", Color.WHITE);
        UIManager.put("Button.focus", new Color(200, 230, 201));

        String message = "<html><body style='text-align:center; font-size:13px;'>"
                + "<b style='color:#388E3C;'>✔ Categoría modificada correctamente</b><br>"
                + "El nombre de la categoría ha sido actualizado."
                + "</body></html>";

        Icon icon = UIManager.getIcon("OptionPane.informationIcon");

        JOptionPane.showMessageDialog(
                this,
                message,
                "Éxito",
                JOptionPane.INFORMATION_MESSAGE,
                icon
        );

        // refrescar lista de categorías
        if (panelCategorias != null) {
            panelCategorias.cargarCategorias();
        }

        // cerrar diálogo
        SwingUtilities.getWindowAncestor(this).dispose();
    } else {
        JOptionPane.showMessageDialog(this,
                "Ocurrió un error al modificar la categoría.",
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_jButton2ActionPerformed

